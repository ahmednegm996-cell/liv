  'اكتب ٣ حاجات إنت شاكر عليها النهاردة',
  'نضف مكان شغلك أو غرفتك',
  'اقرأ ١٠ صفحات من كتاب',
  'نام قبل الساعة ١١',
  'متاكلش أكل جاهز النهاردة',
  'اعمل ١٥ دقيقة رياضة',
  'ابعد عن الموبايل أول نص ساعة من الصبح',
  'خطط ليومك بالكامل قبل ما تبدأه',
  'قول حاجة كويسة لحد قابلته النهاردة',
  'راجع أهدافك الشهرية',
  'جرب تاكل حاجة صحية جديدة',
];

String dailyChallengeFor(String dateKey) {
  final hash = dateKey.codeUnits.fold<int>(0, (a, b) => a + b);
  return _challenges[hash % _challenges.length];
}
